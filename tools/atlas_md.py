"""Write docs/kb/mechanics-atlas.md from docs/kb/mechanics-atlas.json.

    python tools/atlas_md.py
"""
import json
from collections import Counter
from pathlib import Path

KB = Path(__file__).resolve().parent.parent / "docs" / "kb"
ORDER = ["flow", "frontend", "movement", "combat", "armor", "deathblows", "arts", "items", "status",
         "progression", "ai", "stealth", "bosses", "camera", "interface", "map", "visuals", "sound",
         "npcs", "cutscenes", "dialogue"]


def has(h):
    return (h or {}).get("has", "?")


def main():
    recs = json.loads((KB / "mechanics-atlas.json").read_text(encoding="utf-8"))
    cats = ORDER + sorted({r["category"] for r in recs} - set(ORDER))
    needed_by = {}
    for r in recs:
        for n in r.get("needs", []):
            needed_by.setdefault(n["id"], []).append(r["id"])
    out = ["# Sekiro Mechanics Atlas", "",
           "Generated by `python tools/atlas_md.py` from `mechanics-atlas.json` (edit the JSON, not this file).",
           "Each record: what it is, exact values, which system drives it, sources, confidence,",
           "coverage in RustSekiro (ours) and sekiro-rs (his), what it needs, and how to check it.",
           "The ordered playthrough is also written up in `game-flow.md`.", "",
           f"{len(recs)} records. Verdicts: " + ", ".join(f"{k} {v}" for k, v in Counter(r.get('verdict', 'unchecked') for r in recs).items()) + ".", "",
           "| Category | Records | Ours yes/partial/no | His yes/partial/no |", "|---|---|---|---|"]
    for c in cats:
        rs = [r for r in recs if r["category"] == c]
        if not rs:
            continue
        o = Counter(has(r.get("ours")) for r in rs)
        h = Counter(has(r.get("his")) for r in rs)
        out.append(f"| [{c}](#{c}) | {len(rs)} | {o['yes']}/{o['partial']}/{o['no']} | {h['yes']}/{h['partial']}/{h['no']} |")
    for c in cats:
        rs = sorted((r for r in recs if r["category"] == c), key=lambda r: r["id"])
        if not rs:
            continue
        out += ["", f"## {c}"]
        for r in rs:
            out += ["", f"### {r['title']}", f"`{r['id']}` · {r.get('confidence', '?')} · {r.get('verdict', 'unchecked')} · ours {has(r.get('ours'))} · his {has(r.get('his'))}"
                    + (" · **needs a recording**" if r.get("needs_recording") else ""), ""]
            out.append(r.get("summary", ""))
            for label, key in (("Values", "values"), ("How", "how"), ("Check", "check"), ("Note", "note")):
                if r.get(key):
                    out.append(f"- {label}: {r[key]}")
            for side in ("ours", "his"):
                if (r.get(side) or {}).get("where"):
                    out.append(f"- {side}: `{r[side]['where']}`")
            if r.get("needs"):
                out.append("- Needs: " + ", ".join(f"`{n['id']}`" for n in r["needs"]))
            if needed_by.get(r["id"]):
                out.append("- Needed by: " + ", ".join(f"`{i}`" for i in needed_by[r["id"]]))
            if r.get("sources"):
                out.append("- Sources: " + "; ".join(f"{s['kind']}: {s['ref']}" for s in r["sources"]))
    (KB / "mechanics-atlas.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {len(recs)} records")


if __name__ == "__main__":
    main()
